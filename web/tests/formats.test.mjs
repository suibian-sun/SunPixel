import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

import { buildPalette, createMatcher } from '../js/core/color.js';
import { pixelate } from '../js/core/pixelate.js';
import { BLOCK_DATA } from '../js/block-data.js';
import { generateOutput } from '../js/formatter.js';
import { toBedrockOrder } from '../js/format/mcstructure.js';

const here = dirname(fileURLToPath(import.meta.url));

/** 4×2 的测试图：第一行 3 个红 + 1 个白；第二行 红 / 透明 / 黑 / 黑 */
function sampleImage() {
  const width = 4;
  const height = 2;
  const data = new Uint8ClampedArray(width * height * 4);
  const colors = [
    [200, 30, 30, 255], [200, 30, 30, 255], [200, 30, 30, 255], [240, 240, 240, 255],
    [200, 30, 30, 255], [0, 0, 0, 0], [40, 40, 40, 255], [40, 40, 40, 255]
  ];
  colors.forEach((c, i) => data.set(c, i * 4));
  return { width, height, data };
}

function buildResult(options = {}) {
  const matcher = createMatcher(buildPalette(['wool', 'concrete'], BLOCK_DATA), 'lab');
  return pixelate(sampleImage(), matcher, { plane: 'xz', ...options });
}

async function writeOutputs(result, directory) {
  for (const format of ['schem', 'litematic', 'mcstructure', 'nbt', 'mcfunction', 'json', 'blueprint', 'csv']) {
    const output = await generateOutput(result, format, 'sample');
    const buffer = Buffer.from(await output.blob.arrayBuffer());
    writeFileSync(join(directory, output.filename), buffer);
  }
}

function runValidator(directory) {
  const script = join(here, 'validate_nbt.py');
  const stdout = execFileSync('python3', [script, directory], { encoding: 'utf8' });
  return JSON.parse(stdout);
}

test('导出文件能被独立的 nbtlib 正确解析', async (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'sunpixel-'));
  const result = buildResult();
  await writeOutputs(result, directory);
  const report = runValidator(directory);

  await t.test('schem：尺寸、调色板、VarInt 方块数据', () => {
    assert.ok(!report.schem.error, report.schem.error);
    assert.equal(report.schem.width, 4);
    assert.equal(report.schem.height, 1);
    assert.equal(report.schem.length, 2);
    assert.equal(report.schem.version, 2);
    assert.equal(report.schem.paletteSize, result.palette.length);
    assert.equal(report.schem.palette[0], 'minecraft:air');
    assert.deepEqual(report.schem.blocks, Array.from(result.volume));
    assert.equal(report.schem.hasOffset, true);
    assert.equal(report.schem.paletteMax, result.palette.length);
    assert.equal(report.schem.blockEntities, 0);
  });

  await t.test('litematic：BlockStates 解包后与体素一一对应', () => {
    assert.ok(!report.litematic.error, report.litematic.error);
    assert.equal(report.litematic.version, 6);
    assert.deepEqual(report.litematic.palette, result.palette);
    assert.deepEqual(report.litematic.size, [4, 1, 2]);
    assert.deepEqual(report.litematic.enclosing, [4, 1, 2]);
    assert.ok(report.litematic.stateCount >= 8, '解包后的状态数应不少于体素数量');
    assert.deepEqual(report.litematic.states, Array.from(result.volume));
    assert.equal(report.litematic.totalBlocks, result.totalBlocks);
    assert.equal(report.litematic.regionCount, 1);
  });

  await t.test('mcstructure：基岩版索引顺序与双层结构', () => {
    assert.ok(!report.mcstructure.error, report.mcstructure.error);
    assert.deepEqual(report.mcstructure.size, [4, 1, 2]);
    assert.equal(report.mcstructure.formatVersion, 1);
    assert.deepEqual(report.mcstructure.palette, result.palette);
    // 基岩版索引顺序与内部 volume 一致（x 变化最快），不能对调 X/Z
    const expected = Array.from(toBedrockOrder(result.volume));
    assert.deepEqual(report.mcstructure.indices, expected);
    assert.equal(report.mcstructure.secondLayer.length, expected.length);
    assert.ok(report.mcstructure.secondLayer.every((v) => v === -1));
    assert.deepEqual(report.mcstructure.origin, [0, 0, 0]);
  });

  await t.test('nbt：结构方块文件能逐方块还原', () => {
    assert.ok(!report.nbt.error, report.nbt.error);
    assert.deepEqual(report.nbt.size, [4, 1, 2]);
    assert.deepEqual(report.nbt.palette, result.palette);
    assert.deepEqual(report.nbt.states, Array.from(result.volume));
    assert.equal(report.nbt.blockCount, result.totalBlocks);
    assert.equal(report.nbt.hasEntities, true);
    assert.equal(report.nbt.author, 'SunPixel');
  });
});

test('mcfunction 会合并连续方块并用相对坐标', async () => {
  const result = buildResult();
  const output = await generateOutput(result, 'mcfunction', 'sample');
  const text = await output.blob.text();
  assert.match(text, /^# Generated by SunPixel/m);
  assert.match(text, /fill ~0 ~0 ~0 ~2 ~0 ~0 minecraft:red_wool/);
  assert.match(text, /fill ~2 ~0 ~1 ~3 ~0 ~1 minecraft:black_wool/);
  assert.equal(output.info.commands, 4);
  assert.ok(!text.includes('minecraft:air'), '空气不应该出现在命令里');
});

test('RunAway JSON 保留旧字段并带统计信息', async () => {
  const result = buildResult();
  const output = await generateOutput(result, 'json', 'sample');
  const data = JSON.parse(await output.blob.text());
  assert.equal(data.format, 'RunAway');
  assert.deepEqual(data.dimensions, { width: 4, height: 1, depth: 2 });
  assert.equal(data.blocks.length, 8);
  assert.equal(data.statistics.block_types, result.counts.size);
  assert.equal(data.statistics.air_count, 1);
});

test('手动搭建图纸包含图例、材料清单与全部行', async () => {
  const result = buildResult();
  const output = await generateOutput(result, 'blueprint', 'sample');
  const text = await output.blob.text();
  assert.match(text, /## 材料清单/);
  assert.match(text, /## 图例/);
  assert.match(text, /\| \. \| 空气 \|/);
  const rows = text.split('```text')[1].split('\n').slice(2).filter((line) => line.startsWith(' '));
  assert.ok(rows.length >= 2, '应至少有 2 行图纸');
  assert.equal(output.filename, 'sample.md');
});

test('材料清单 CSV 行数等于实心方块数', async () => {
  const result = buildResult();
  const output = await generateOutput(result, 'csv', 'sample');
  const lines = (await output.blob.text()).trim().split('\n');
  assert.equal(lines[0], 'x,y,z,block');
  assert.equal(lines.length - 1, result.totalBlocks);
});

test('竖立结构的图纸直接给正面图，不按层拆开', async () => {
  const result = buildResult({ plane: 'xy' });
  assert.equal(result.size.y, 2, '测试前提：竖立时应有两层高度');

  const output = await generateOutput(result, 'blueprint', 'wall');
  const text = await output.blob.text();

  assert.ok(!text.includes('### Y ='), '竖立结构不该按层出图');
  assert.equal((text.match(/```text/g) || []).length, 1, '应只有一张正面图');
  assert.match(text, /竖立，贴墙/);
});

test('调色板超过 127 种方块时，VarInt 与位打包依旧正确', async () => {
  // 直接构造一份"大调色板"结构：索引会超过 127，VarInt 必须变成 2 字节，
  // 位打包也要跨 long 拼接——旧实现两种都会写坏。
  const palette = ['minecraft:air'];
  for (let i = 1; i < 201; i++) palette.push(`minecraft:test_block_${i}`);
  const size = { x: 8, y: 1, z: 8 };
  const volume = new Int32Array(64);
  for (let i = 0; i < 64; i++) volume[i] = i * 3 % 201;
  const result = {
    width: 8,
    height: 8,
    plane: 'xz',
    size,
    palette,
    volume,
    counts: new Map(),
    airIndex: 0,
    totalBlocks: 60,
    totalVolume: 64
  };

  const directory = mkdtempSync(join(tmpdir(), 'sunpixel-big-'));
  for (const format of ['schem', 'litematic', 'nbt']) {
    const output = await generateOutput(result, format, 'sample');
    writeFileSync(join(directory, output.filename), Buffer.from(await output.blob.arrayBuffer()));
  }
  const report = runValidator(directory);

  assert.ok(!report.schem.error, report.schem.error);
  assert.deepEqual(report.schem.blocks, Array.from(volume), 'VarInt 解码结果不一致');
  assert.ok(!report.litematic.error, report.litematic.error);
  assert.deepEqual(report.litematic.states, Array.from(volume), '位打包解码结果不一致');
  assert.equal(report.litematic.palette.length, 201);
  assert.ok(!report.nbt.error, report.nbt.error);
  assert.deepEqual(report.nbt.states, Array.from(volume), '结构方块文件还原结果不一致');
  assert.equal(report.nbt.palette.length, 201);
});
