/** 像素画坐标 → 世界坐标（~ 相对坐标原点） */
function worldPosition(result, px, py) {
  if (result.plane === 'xy') {
    return { x: px, y: result.height - 1 - py, z: 0 };
  }
  return { x: px, y: 0, z: py };
}

/**
 * .mcfunction：用 fill 合并同行连续同种方块，命令数量通常降到 1/5 以内。
 * 相比旧版本（每个方块一条 setblock）在大图上明显更快，也不容易触发命令上限。
 */
function generateMcfunction(result, meta = {}) {
  const { width, height, grid, palette } = result;
  const lines = [];
  lines.push('# Generated by SunPixel');
  lines.push(`# ${meta.name || '像素画'} · ${width} × ${height}`);
  lines.push('# 用法：站在目标位置，面向 +Z 方向执行 function <命名空间>:<文件名>');
  lines.push('# 坐标原点为命令执行方块所在位置，Y 轴向上');
  lines.push('');

  let fillCount = 0;
  let setCount = 0;
  let skipped = 0;

  for (let py = 0; py < height; py++) {
    let px = 0;
    while (px < width) {
      const index = grid[py * width + px];
      if (index === 0) {
        skipped++;
        px++;
        continue;
      }

      let end = px;
      while (end + 1 < width && grid[py * width + end + 1] === index) end++;

      const block = palette[index];
      const start = worldPosition(result, px, py);
      const stop = worldPosition(result, end, py);

      if (px === end) {
        lines.push(`setblock ~${start.x} ~${start.y} ~${start.z} ${block}`);
        setCount++;
      } else {
        lines.push(`fill ~${start.x} ~${start.y} ~${start.z} ~${stop.x} ~${stop.y} ~${stop.z} ${block}`);
        fillCount++;
      }
      px = end + 1;
    }
  }

  const content = lines.join('\n') + '\n';
  return {
    blob: new Blob([content], { type: 'text/plain;charset=utf-8' }),
    info: { commands: fillCount + setCount, fills: fillCount, setblocks: setCount, skippedRows: skipped }
  };
}

export { generateMcfunction, worldPosition };
