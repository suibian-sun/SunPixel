import { NBTWriter, gzipCompress } from './nbt-writer.js';

// 生成 .schem 格式 (Sponge Schematic)
async function generateSchem(result) {
  const { width, height, depth, blockPalette, blockData } = result;
  
  const nbt = new NBTWriter();
  
  // Sponge Schematic v2
  const schemData = {
    Version: { value: 2, tag: 1 }, // TAG_Byte
    DataVersion: { value: 2975, tag: 3 }, // TAG_Int
    Metadata: {
      WEOffsetX: { value: 0, tag: 3 },
      WEOffsetY: { value: 0, tag: 3 },
      WEOffsetZ: { value: 0, tag: 3 },
      Name: "SunPixel"
    },
    Width: { value: width, tag: 2 }, // TAG_Short
    Height: { value: height, tag: 2 },
    Length: { value: depth, tag: 2 },
    OffsetX: { value: 0, tag: 3 },
    OffsetY: { value: 0, tag: 3 },
    OffsetZ: { value: 0, tag: 3 },
    Palette: {},
    BlockData: { value: new Uint8Array(blockData), tag: 7 }, // TAG_ByteArray
    BlockEntities: { type: 10, items: [] }
  };
  
  // 构建调色板
  const paletteEntries = {};
  blockPalette.forEach((name, idx) => {
    paletteEntries[name] = idx;
  });
  schemData.Palette = paletteEntries;
  
  // 写入 NBT
  nbt.writeTag(10, '', schemData);
  const rawBytes = nbt.getBytes();
  
  // GZip 压缩
  const compressed = await gzipCompress(rawBytes);
  
  return new Blob([compressed], { type: 'application/octet-stream' });
}

// 生成 .json 格式 (RunAway格式)
function generateJson(result) {
  const { width, height, blockPalette, blockData, blockCounts } = result;
  
  const jsonData = {
    format: "RunAway",
    version: 2,
    generated_by: "SunPixel",
    dimensions: { width, height, depth: 1 },
    palette: blockPalette,
    blocks: blockData,
    statistics: {
      block_count: Object.values(blockCounts).reduce((a, b) => a + b, 0),
      block_types: Object.keys(blockCounts).length,
      block_details: blockCounts
    }
  };
  
  const jsonStr = JSON.stringify(jsonData, null, 2);
  return new Blob([jsonStr], { type: 'application/json' });
}

// 生成 .mcfunction 格式 (命令方块函数)
function generateMcfunction(result) {
  const { width, height, blockPalette, blockData } = result;
  
  let commands = [];
  commands.push(`# Generated by SunPixel`);
  commands.push(`# Dimensions: ${width} x ${height} x 1`);
  commands.push(`# ${new Date().toISOString()}`);
  commands.push(``);
  
  // 先用 fill 命令填充空气
  commands.push(`fill ~ ~ ~ ~${width-1} ~ ~${0} air`);
  commands.push(``);
  
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = y * width + x;
      const paletteIdx = blockData[idx];
      const blockName = blockPalette[paletteIdx];
      const z = 0;
      commands.push(`setblock ~${x} ~${y} ~${z} ${blockName}`);
    }
  }
  
  const content = commands.join('\n');
  return new Blob([content], { type: 'text/plain' });
}

// 生成 .litematic 格式 (简化版)
async function generateLitematic(result) {
  const { width, height, blockPalette, blockData } = result;
  
  // 简化的 litematic 格式 - 使用 NBT
  const nbt = new NBTWriter();
  
  const regions = {};
  const regionBlocks = {};
  blockPalette.forEach((name, idx) => {
    regionBlocks[name] = { value: idx, tag: 3 };
  });
  
  const litematicData = {
    Version: { value: 6, tag: 3 },
    MinecraftDataVersion: { value: 2975, tag: 3 },
    Metadata: {
      Author: "SunPixel",
      Description: "Generated by SunPixel",
      Name: "SunPixel Build",
      TimeCreated: { value: BigInt(Date.now()), tag: 4 },
      TimeModified: { value: BigInt(Date.now()), tag: 4 },
      TotalBlocks: { value: blockData.length, tag: 3 },
      TotalVolume: { value: width * height, tag: 3 }
    },
    Regions: {
      "main": {
        Position: { x: 0, y: 0, z: 0 },
        Size: { x: width, y: height, z: 1 },
        BlockPalette: {
          type: 10,
          items: blockPalette.map(name => ({ Name: name, Properties: {} }))
        },
        BlockStates: { value: new BigUint64Array(blockData.length), tag: 12 },
        Entities: { type: 10, items: [] },
        TileEntities: { type: 10, items: [] }
      }
    }
  };
  
  nbt.writeTag(10, '', litematicData);
  const rawBytes = nbt.getBytes();
  const compressed = await gzipCompress(rawBytes);
  
  return new Blob([compressed], { type: 'application/octet-stream' });
}

// 生成 .bdx 格式 (简化版)
function generateBdx(result) {
  const { blockPalette, blockData } = result;
  
  // BDX 格式使用简单的二进制编码
  const encoder = new TextEncoder();
  const lines = [];
  
  lines.push('BDX§');
  lines.push('VERSION§1');
  lines.push(`AUTHOR§SunPixel`);
  lines.push(`DATE§${Date.now()}`);
  lines.push(`BLOCK_COUNT§${blockData.length}`);
  lines.push(`PALETTE_SIZE§${blockPalette.length}`);
  
  blockPalette.forEach((name, idx) => {
    lines.push(`PALETTE§${idx}§${name}`);
  });
  
  lines.push(`DATA§${blockData.join(',')}`);
  lines.push('END§');
  
  const content = lines.join('\n');
  return new Blob([content], { type: 'application/octet-stream' });
}

// 生成 .mcstructure 格式 (简化版)
async function generateMcstructure(result) {
  const { width, height, blockPalette, blockData } = result;
  
  const nbt = new NBTWriter();
  
  const structureData = {
    format_version: { value: 1, tag: 3 },
    size: [width, height, 1],
    structure: {
      block_indices: {
        type: 11,
        items: [
          { type: 3, items: blockData.map(v => v) },
          { type: 3, items: new Array(blockData.length).fill(-1) }
        ]
      },
      entities: { type: 10, items: [] },
      palette: {
        default: {
          block_palette: {
            type: 10,
            items: blockPalette.map(name => ({
              name: name,
              states: {},
              version: 18092879
            }))
          },
          block_position_data: { type: 10, items: [] }
        }
      }
    },
    structure_world_origin: [0, 0, 0]
  };
  
  nbt.writeTag(10, '', structureData);
  const rawBytes = nbt.getBytes();
  const compressed = await gzipCompress(rawBytes);
  
  return new Blob([compressed], { type: 'application/octet-stream' });
}

