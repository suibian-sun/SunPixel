// 主生成函数
async function generateOutput(result, format, filename) {
  let blob;
  let ext = format;
  
  switch (format) {
    case 'schem':
      blob = await generateSchem(result);
      break;
    case 'json':
      blob = generateJson(result);
      break;
    case 'mcfunction':
      blob = generateMcfunction(result);
      break;
    case 'litematic':
      blob = await generateLitematic(result);
      break;
    case 'bdx':
      blob = generateBdx(result);
      break;
    case 'mcstructure':
      blob = await generateMcstructure(result);
      break;
    case 'mcworld':
      blob = await generateMcworld(result);
      break;
    default:
      blob = generateJson(result);
      ext = 'json';
  }
  
  const finalName = filename || `sunpixel_build.${ext}`;
  return { blob, filename: finalName };
}

export { generateOutput };